#!/usr/bin/env python3
"""Generate the data of the proved numerical facts of the paper.

  CpsLean/PrimeCertData.lean  Lucas (Pratt) certificates: N_n is prime, n = 1..20 (Table 1).
  CpsLean/LiGridData.lean     a rational grid bounding li from below and above up to 109^2.
  CpsLean/Table1Data.lean     the rows of Table 1, from table1_cert.txt.

Usage (from lean/): gen_numerics.py          Requires sympy.
"""
import math
from fractions import Fraction as F
from sympy import factorint, isprime, n_order, primitive_root, primerange

NUM = "scripts/numerics/"
SMALL = 10 ** 6  # below this, norm_num proves primality
HDR = "module\n\npublic import CpsLean.%s\nset_option autoImplicit false\n\n/-! %s\nGenerated by `scripts/numerics/gen_numerics.py`. -/\n\n@[expose] public section\n\nnamespace CpsLean\n\n"
rows = [l.split() for l in open(NUM + "table1_cert.txt")]

# --- Lucas certificates -------------------------------------------------------------------------
done, out = {}, []


def cert(p):
    if p in done or p < SMALL:
        return
    assert isprime(p) and p - 1 < 2 ** 64
    fac = factorint(p - 1)
    for q in fac:
        cert(q)
    a = primitive_root(p)
    fs = [q for q, e in sorted(fac.items()) for _ in range(e)]
    big = [q for q in fac if q >= SMALL]
    tac = " ".join(f"exact prime_{q} |" for q in big)
    out.append(
        f"theorem prime_{p} : Nat.Prime {p} :=\n"
        f"  prime_of_lucas {p} {a} {fs} (by norm_num)\n"
        f"    (by intro q hq; simp only [List.mem_cons, List.not_mem_nil, or_false] at hq\n"
        f"        rcases hq with {' | '.join(['rfl'] * len(fs))} <;> first | {tac} norm_num)\n"
        f"    (by norm_num) (by norm_num) (by decide +kernel) (by decide +kernel)\n"
    )
    done[p] = 1


Ns = [int(r[3]) for r in rows]
for N in Ns:
    cert(N)
names = []
for N in Ns:
    names.append(f"prime_{N}" if N >= SMALL else f"(by norm_num : Nat.Prime {N})")
with open("CpsLean/PrimeCertData.lean", "w") as f:
    f.write(HDR % ("Pratt", "Lucas certificates: the primes `N_n` of Table 1."))
    f.write("\n".join(out))
    f.write("\nend CpsLean\n")

# --- Table 1 ------------------------------------------------------------------------------------
with open("CpsLean/Table1Data.lean", "w") as f:
    f.write(HDR % ("PrimeCertData", "The rows of Table 1, `(n, lo, hi, N_n)`; the denominator of `lo`, `hi` is `10²⁴`."))
    f.write("/-- The rows `(n, lo, hi, N_n)` of Table 1: `lo/10²⁴ < γ_n < hi/10²⁴` is the Arb ball of `γ_n`. -/\n")
    f.write("def table1Rows : List (ℕ × ℕ × ℕ × ℕ) :=\n  [")
    f.write(",\n   ".join(f"({r[0]}, {r[1]}, {r[2]}, {r[3]})" for r in rows))
    f.write("]\n\n")
    f.write("/-- The first-crossing primes `N_n` of Table 1 are prime. -/\n")
    f.write("theorem table1_primes : ∀ r ∈ table1Rows, Nat.Prime r.2.2.2 := by\n")
    f.write("  intro r hr\n  simp only [table1Rows, List.mem_cons, List.not_mem_nil, or_false] at hr\n")
    f.write("  rcases hr with " + " | ".join(["rfl"] * len(rows)) + "\n")
    f.write("".join(f"  · exact {n}\n" for n in names))
    f.write("\nend CpsLean\n")

# --- li grid ------------------------------------------------------------------------------------
K, LU, LL = 64, 6931471808, 6931471803
R, SC = 1.07, 10 ** 4


def build():
    pts, x = {16}, 2.0
    while x < 11881:
        x *= R
        pts.add(math.ceil(x * 8))
    pts = {p for p in pts if p < 8 * 11881}
    pts |= {8 * p * p for p in primerange(2, 110)}
    return sorted(pts)


def mU(b):
    m = math.ceil(K * math.log2(b / 8))
    while b ** K > 2 ** m * 8 ** K:
        m += 1
    return m


def mL(b):
    m = math.floor(K * math.log2(b / 8))
    while 2 ** m * 8 ** K > b ** K:
        m -= 1
    return m


pts = build()
assert pts[0] == 16 and pts[-1] == 8 * 11881
L, U, grid = SC // 2, 2 * SC, []
for a, b in zip(pts, pts[1:]):
    mu, ml_a, ml_b = mU(b), mL(a), mL(b)
    den = 64 * 10 ** 10
    # L' <= L + (b-a)/8 / ((mu/64) LOG2U), in units of 1/SC
    L = L + ((b - a) * SC * den) // (8 * mu * LU)
    # U' >= U + (b-a)/8 / ((ml_a/64) LOG2L)
    d, r = divmod((b - a) * SC * den, 8 * ml_a * LL)
    U = U + d + (1 if r else 0)
    grid.append((b, mu, ml_b, L, U))
with open("CpsLean/LiGridData.lean", "w") as f:
    f.write(HDR % ("LiGrid", "The grid `(8b, mU, mL, L, U)` of `li`; see `liChainOk`."))
    f.write("/-- The grid of `li`: `y = b/8`, `mL/64 · log 2 ≤ log y ≤ mU/64 · log 2`, `L/10⁴ ≤ li y ≤ U/10⁴`. -/\n")
    f.write("def liGrid : List (ℕ × ℕ × ℕ × ℕ × ℕ) :=\n  [")
    f.write(",\n   ".join(f"({b}, {a}, {c}, {d}, {e})" for b, a, c, d, e in grid))
    f.write("]\n\nend CpsLean\n")
print("primes", len(done), "grid", len(grid), "final", grid[-1], float(F(grid[-1][4], SC)))
